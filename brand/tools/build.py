#!/usr/bin/env python3
"""Builds the Marcus Lab brand files from tokens/marcuslab.tokens.json.

    python3 brand/tools/build.py            # tokens.css, contrast.md, every logo SVG
    python3 brand/tools/build.py --png      # also the PNG exports (needs rsvg-convert and Google Chrome)

Nothing here is edited by hand afterwards: change the tokens, run this again.
"""
import json, math, re, shutil, subprocess, sys, tempfile
from pathlib import Path

BRAND = Path(__file__).resolve().parent.parent
T = json.loads((BRAND / "tokens" / "marcuslab.tokens.json").read_text())
SVG, PNG = BRAND / "logo" / "svg", BRAND / "logo" / "png"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"


# ---------------------------------------------------------------- tokens → CSS
def walk(node, path=()):
    for k, v in node.items():
        if k.startswith("$"):
            continue
        if isinstance(v, dict) and "$value" in v:
            yield path + (k,), v
        elif isinstance(v, dict):
            yield from walk(v, path + (k,))

def css_value(path, tok):
    v = tok["$value"]
    if isinstance(v, str) and (m := re.fullmatch(r"\{(.+)\}", v)):
        return f"var(--ml-{m.group(1).replace('.', '-')})"
    if path[:2] == ("font", "family"):
        return ", ".join(f'"{f}"' if " " in f else f for f in v)
    if path[:2] == ("motion", "ease"):
        return f"cubic-bezier({', '.join(str(n) for n in v)})"
    return str(v)

def resolve(ref):
    node = T
    for part in ref.split("."):
        node = node[part]
    v = node["$value"]
    return resolve(v[1:-1]) if isinstance(v, str) and v.startswith("{") else v

def build_css():
    lines = ["/* Marcus Lab design tokens. Generated by brand/tools/build.py from marcuslab.tokens.json: do not edit. */", ":root{"]
    group = None
    for path, tok in walk(T):
        if path[0] in ("logo", "project-marks"):
            continue
        if path[0] != group:
            group = path[0]; lines.append(f"\n  /* {group} */")
        note = f"  /* {tok['$description']} */" if "$description" in tok else ""
        lines.append(f"  --ml-{'-'.join(path)}: {css_value(path, tok)};{note}")
    lines.append("}\n")
    (BRAND / "tokens" / "tokens.css").write_text("\n".join(lines))


# ---------------------------------------------------------------- contrast
def lum(hexcol):
    r, g, b = (int(hexcol[i:i + 2], 16) / 255 for i in (1, 3, 5))
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)

def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)

def build_contrast():
    c = lambda ref: resolve("color." + ref)
    pairs = [("Cream text on the dark ground", "cream.100", "ink.900"), ("Cream text on a raised surface", "cream.100", "ink.800"),
             ("Cream text on the mat", "cream.100", "olive.500"), ("Cream text on the desk", "cream.100", "wood.500"),
             ("Orange text on the dark ground", "orange.500", "ink.900"), ("Ink text on orange", "ink.900", "orange.500"),
             ("Cream text on orange", "cream.100", "orange.500"), ("Ink text on cream", "ink.900", "cream.100"),
             ("Orange on the mat", "orange.500", "olive.500"), ("Orange on cream", "orange.500", "cream.100")]
    pairs += [(f"{k.capitalize()} colour on the dark ground", f"type.{k}", "ink.900") for k in ("app", "server", "hardware", "printed", "odds")]
    pairs += [("Live lamp on the dark ground", "status.live", "ink.900")]
    rows = ["# Contrast", "", "Generated by `brand/tools/build.py`. WCAG 2.1: body text needs 4.5, large text (24px, or 19px bold) and graphics need 3.", "",
            "| Pair | Ratio | Body text | Large text and graphics |", "|---|---|---|---|"]
    for name, fg, bg in pairs:
        r = ratio(c(fg), c(bg))
        rows.append(f"| {name} | {r:.1f} | {'pass' if r >= 4.5 else 'FAIL'} | {'pass' if r >= 3 else 'FAIL'} |")
    (BRAND / "tokens" / "contrast.md").write_text("\n".join(rows) + "\n")


# ---------------------------------------------------------------- the mark
L = {k: v["$value"] for k, v in T["logo"].items() if not k.startswith("$")}
OUT, CX = L["outline"], L["centre-x"]
INK, CREAM, OLIVE, ORANGE = (resolve(f"color.{r}") for r in ("ink.900", "cream.100", "olive.500", "orange.500"))

def hatch(fg):
    """45° lines at the token pitch, drawn as plain lines so every renderer agrees."""
    step = L["hatch-pitch"] * math.sqrt(2)
    xs, x = [], CX - 64 - step * 4
    while x < 64:
        xs.append(x); x += step
    return "".join(f'<path d="M{x:.2f} 64 L{x + 64:.2f} 0"/>' for x in xs)

def mark(fg, line, uid="m", arrows=False):
    """The Section A–A mark: solid left half, hatched right half, an outline, and the chain centre line."""
    y0, y1 = (4, 60) if arrows else (8, 56)
    extra = ""
    if arrows:
        a = lambda y: f'<path d="M{CX} {y} H42 M39.4 {y - 2.3} L42.5 {y} L39.4 {y + 2.3}"/>'
        extra = f'<g fill="none" stroke="{line}" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">{a(4)}{a(60)}</g>'
    return (f'<defs><clipPath id="{uid}l"><rect x="0" y="0" width="{CX}" height="64"/></clipPath>'
            f'<clipPath id="{uid}r"><rect x="{CX}" y="0" width="{64 - CX}" height="64"/></clipPath>'
            f'<clipPath id="{uid}o"><polygon points="{OUT}"/></clipPath></defs>'
            f'<polygon points="{OUT}" fill="{fg}" clip-path="url(#{uid}l)"/>'
            f'<g clip-path="url(#{uid}r)"><g clip-path="url(#{uid}o)" fill="none" stroke="{fg}" stroke-width="{L["hatch-width"]}">{hatch(fg)}</g></g>'
            f'<polygon points="{OUT}" fill="none" stroke="{fg}" stroke-width="{L["edge-width"]}" stroke-linejoin="miter"/>'
            f'<path d="M{CX} {y0} V{y1}" fill="none" stroke="{line}" stroke-width="{L["line-width"]}" stroke-dasharray="{L["line-dash"]}"/>{extra}')

def micro(fg, uid="u"):
    """For 16 to 23 px: no hatching or line. Solid left half, lighter right half, a gap where the cut is."""
    return (f'<defs><clipPath id="{uid}l"><rect x="0" y="0" width="{CX - 1.4}" height="64"/></clipPath>'
            f'<clipPath id="{uid}r"><rect x="{CX + 1.4}" y="0" width="{64 - CX}" height="64"/></clipPath></defs>'
            f'<polygon points="{OUT}" fill="{fg}" clip-path="url(#{uid}l)"/><polygon points="{OUT}" fill="{fg}" fill-opacity=".5" clip-path="url(#{uid}r)"/>')

def svg(name, viewbox, body, title, w=None, h=None):
    x, y, vw, vh = viewbox
    size = f' width="{w or vw}" height="{h or vh}"'
    (SVG / name).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {vw} {vh}"{size} role="img" aria-label="{title}"><title>{title}</title>{body}</svg>\n')

def tile(bg, inner, scale=.8):
    return f'<rect width="64" height="64" rx="14" fill="{bg}"/><g transform="translate(32 32) scale({scale}) translate(-32 -32)">{inner}</g>'

def text(x, y, size, track, fill, anchor="start"):
    return (f'<text x="{x}" y="{y}" text-anchor="{anchor}" font-family="Outfit, system-ui, sans-serif" font-weight="700" font-size="{size}" '
            f'letter-spacing="{track}" fill="{fill}">MARCUS LAB</text>')

def build_logos():
    SVG.mkdir(parents=True, exist_ok=True)
    sq, full, mi = (4, 4, 56, 56), (0, -2, 64, 68), (8, 8, 48, 48)
    for name, fg, line in (("cream", CREAM, ORANGE), ("ink", INK, ORANGE), ("mono-cream", CREAM, CREAM), ("mono-ink", INK, INK),
                           ("mono-white", "#ffffff", "#ffffff"), ("mono-black", "#000000", "#000000")):
        svg(f"mark-{name}.svg", sq, mark(fg, line), "Marcus Lab mark")
        svg(f"mark-full-{name}.svg", full, mark(fg, line, arrows=True), "Marcus Lab mark with section arrows")
    for name, fg in (("cream", CREAM), ("ink", INK)):
        svg(f"mark-micro-{name}.svg", mi, micro(fg), "Marcus Lab mark, small sizes")
    for name, bg, fg in (("olive", OLIVE, CREAM), ("ink", INK, CREAM), ("cream", CREAM, INK)):
        svg(f"icon-{name}.svg", (0, 0, 64, 64), tile(bg, mark(fg, ORANGE)), "Marcus Lab icon", 512, 512)
        svg(f"icon-micro-{name}.svg", (0, 0, 64, 64), tile(bg, micro(fg), .86), "Marcus Lab icon, small sizes", 64, 64)
    # full-bleed square for platforms that round the corners themselves (iOS, Android maskable)
    svg("icon-square-olive.svg", (0, 0, 64, 64), f'<rect width="64" height="64" fill="{OLIVE}"/><g transform="translate(32 32) scale(.7) translate(-32 -32)">{mark(CREAM, ORANGE)}</g>', "Marcus Lab icon", 512, 512)
    # lockups. The name is live text in Outfit 700: use the PNG where the font cannot be guaranteed, outline it before print.
    for name, fg in (("cream", CREAM), ("ink", INK)):
        body = f'<svg x="0" y="4" width="56" height="56" viewBox="4 4 56 56">{mark(fg, ORANGE)}</svg>' + text(68, 41.5, 27, 1.08, fg)
        svg(f"lockup-nameplate-{name}.svg", (0, 0, 262, 64), body, "Marcus Lab")
        body = f'<svg x="66" y="0" width="68" height="72.25" viewBox="0 -2 64 68">{mark(fg, ORANGE, arrows=True)}</svg>' + text(102.7, 96, 15.5, 5.27, fg, "middle")
        svg(f"lockup-signature-{name}.svg", (0, 0, 200, 106), body, "Marcus Lab")


# ---------------------------------------------------------------- project marks
Z = {k: v["$value"] for k, v in T["project-marks"]["zigbrew"].items() if not k.startswith("$")}

def ring(outer, inner, lug, half):
    """A ring with three lugs 120° apart, one at the top, as a single even-odd path about the centre of the square."""
    out, inn = [], []
    for i in range(720):
        deg = i / 2; a = math.radians(deg)
        r = lug if any(abs((deg - c + 180) % 360 - 180) <= half for c in (90, 210, 330)) else outer
        out.append((CX + r * math.cos(a), 32 - r * math.sin(a)))
    for i in range(720, 0, -1):
        a = math.radians(i / 2)
        inn.append((CX + inner * math.cos(a), 32 - inner * math.sin(a)))
    p = lambda pts: "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"
    return p(out) + " " + p(inn)

def shape_mark(d, fg, line, uid="z"):
    """Any closed path drawn by the logo's rules: solid left half, hatched right half, an outline, the chain centre line."""
    return (f'<defs><clipPath id="{uid}l"><rect x="0" y="0" width="{CX}" height="64"/></clipPath>'
            f'<clipPath id="{uid}r"><rect x="{CX}" y="0" width="{64 - CX}" height="64"/></clipPath>'
            f'<clipPath id="{uid}o"><path d="{d}" clip-rule="evenodd"/></clipPath></defs>'
            f'<path d="{d}" fill="{fg}" fill-rule="evenodd" clip-path="url(#{uid}l)"/>'
            f'<g clip-path="url(#{uid}r)"><g clip-path="url(#{uid}o)" fill="none" stroke="{fg}" stroke-width="{L["hatch-width"]}">{hatch(fg)}</g></g>'
            f'<path d="{d}" fill="none" stroke="{fg}" stroke-width="{L["edge-width"]}" stroke-linejoin="miter"/>'
            f'<path d="M{CX} 5 V59" fill="none" stroke="{line}" stroke-width="{L["line-width"]}" stroke-dasharray="{L["line-dash"]}"/>')

def shape_micro(d, fg, uid="y"):
    return (f'<defs><clipPath id="{uid}l"><rect x="0" y="0" width="{CX - 1.4}" height="64"/></clipPath>'
            f'<clipPath id="{uid}r"><rect x="{CX + 1.4}" y="0" width="{64 - CX}" height="64"/></clipPath></defs>'
            f'<path d="{d}" fill="{fg}" fill-rule="evenodd" clip-path="url(#{uid}l)"/>'
            f'<path d="{d}" fill="{fg}" fill-opacity=".5" fill-rule="evenodd" clip-path="url(#{uid}r)"/>')

def build_project_marks():
    big = ring(Z["outer"], Z["inner"], Z["lug"], Z["lug-half"])
    small = ring(Z["micro-outer"], Z["micro-inner"], Z["micro-lug"], Z["micro-lug-half"])
    # the lugs reach further than the M does, so this mark sits in a slightly larger box than the Section A–A mark
    for name, fg, line in (("cream", CREAM, ORANGE), ("ink", INK, ORANGE), ("mono-cream", CREAM, CREAM), ("mono-ink", INK, INK)):
        svg(f"zigbrew-mark-{name}.svg", (2, 2, 60, 60), shape_mark(big, fg, line), "zigbrew mark")
    for name, fg in (("cream", CREAM), ("ink", INK)):
        svg(f"zigbrew-mark-micro-{name}.svg", (6, 6, 52, 52), shape_micro(small, fg), "zigbrew mark, small sizes")
    svg("zigbrew-icon-olive.svg", (0, 0, 64, 64), tile(OLIVE, shape_mark(big, CREAM, ORANGE), .78), "zigbrew icon", 512, 512)
    svg("zigbrew-icon-micro-olive.svg", (0, 0, 64, 64), tile(OLIVE, shape_micro(small, CREAM), .84), "zigbrew icon, small sizes", 64, 64)


# ---------------------------------------------------------------- PNG exports
def rsvg(src, out, px):
    subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), str(SVG / src), "-o", str(PNG / out)], check=True)

def chrome_shot(html, out, w, h, scale=1, transparent=True):
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / "page.html"; page.write_text(html)
        cmd = [CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", f"--force-device-scale-factor={scale}", f"--window-size={w},{h}",
               "--virtual-time-budget=6000", f"--screenshot={PNG / out}", page.as_uri()]
        if transparent:
            cmd.insert(1, "--default-background-color=00000000")
        subprocess.run(cmd, check=True, capture_output=True)

FONTS = '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Outfit:wght@600;700&family=DM+Mono:wght@500&display=swap">'

def build_pngs():
    PNG.mkdir(parents=True, exist_ok=True)
    for px in (16,):
        rsvg("icon-micro-olive.svg", f"favicon-{px}.png", px)
    for px in (32, 48):
        rsvg("icon-olive.svg", f"favicon-{px}.png", px)
    rsvg("icon-square-olive.svg", "apple-touch-icon-180.png", 180)
    for px in (192, 512):
        rsvg("icon-olive.svg", f"icon-{px}.png", px)
        rsvg("icon-square-olive.svg", f"icon-maskable-{px}.png", px)
    for name in ("cream", "ink"):
        rsvg(f"mark-{name}.svg", f"mark-{name}-512.png", 512)
    rsvg("icon-olive.svg", "avatar-400.png", 400)
    rsvg("zigbrew-icon-micro-olive.svg", "zigbrew-favicon-16.png", 16)
    rsvg("zigbrew-icon-olive.svg", "zigbrew-favicon-32.png", 32)
    rsvg("zigbrew-icon-olive.svg", "zigbrew-icon-512.png", 512)
    for name in ("cream", "ink"):
        rsvg(f"zigbrew-mark-{name}.svg", f"zigbrew-mark-{name}-512.png", 512)
    for kind, (w, h) in (("nameplate", (262, 64)), ("signature", (200, 106))):
        for name in ("cream", "ink"):
            body = (SVG / f"lockup-{kind}-{name}.svg").read_text()
            chrome_shot(f'<!doctype html><meta charset="utf-8">{FONTS}<style>html,body{{margin:0;background:transparent}}svg{{display:block;width:{w * 4}px;height:{h * 4}px}}</style>{body}',
                        f"lockup-{kind}-{name}.png", w * 4, h * 4)
    sig = (SVG / "lockup-signature-cream.svg").read_text()
    grid = lambda a, s: f"repeating-linear-gradient(0deg, rgba(255,237,215,{a}) 0 1px, transparent 1px {s}px), repeating-linear-gradient(90deg, rgba(255,237,215,{a}) 0 1px, transparent 1px {s}px)"
    chrome_shot(f'''<!doctype html><meta charset="utf-8">{FONTS}<style>html,body{{margin:0}}
      body{{width:1200px;height:630px;background:{grid(.2, 100)}, {grid(.08, 20)}, {OLIVE};background-position:50% 50%;display:grid;place-items:center;font-family:"DM Mono",monospace;color:{CREAM}}}
      div{{display:flex;flex-direction:column;align-items:center;gap:26px}} svg{{width:520px;height:auto}} p{{margin:0;font-size:19px;letter-spacing:.16em;font-weight:500}}</style>
      <div>{sig}<p>APPS, SERVERS &amp; HARDWARE · MARCUSLAB.UK</p></div>''', "og-image-1200x630.png", 1200, 630, transparent=False)


if __name__ == "__main__":
    build_css(); build_contrast(); build_logos(); build_project_marks()
    print(f"tokens.css, contrast.md and {len(list(SVG.glob('*.svg')))} SVGs written")
    if "--png" in sys.argv:
        if not shutil.which("rsvg-convert") or not Path(CHROME).exists():
            sys.exit("PNG export needs rsvg-convert and Google Chrome")
        build_pngs(); print(f"{len(list(PNG.glob('*.png')))} PNGs written")
